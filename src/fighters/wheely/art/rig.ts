/** The original blinks every few seconds; Flash ran at 35 fps. */
const BLINK_FPS = 35;
const blink = (open: string, hold = 110) => ({
  loop: [
    ...Array<string>(hold).fill(open),
    'eyesBlink1',
    'eyesBlink2',
    'eyesClosed',
    'eyesClosed',
    'eyesBlink2',
    'eyesBlink1',
  ],
  fps: BLINK_FPS,
});

const child = (
  name: string,
  parent: string,
  [x, y]: readonly [number, number],
  [px, py]: readonly [number, number],
): Bone => ({
  name,
  parent,
  x: x - px,
  y: y - py,
});


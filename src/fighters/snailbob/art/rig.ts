/** Outline slots for both segments of a limb, then their fills, so the joint has no seam. */
function limbSlots(upper: string, lower: string, upperSym: string | null, lowerSym: string | null): Slot[] {
  return [
    { name: `${upper}Line`, bone: upper, symbol: upperSym && `${upperSym}Line` },
    { name: `${lower}Line`, bone: lower, symbol: lowerSym && `${lowerSym}Line` },
    { name: upper, bone: upper, symbol: upperSym },
    { name: lower, bone: lower, symbol: lowerSym },
  ];
}

function partSymbols(parts: Record<string, Part>): Record<string, PathShape[]> {
  return Object.fromEntries(
    Object.entries(parts).flatMap(([name, p]) => [
      [name, p.fill],
      [`${name}Line`, p.line],
    ]),
  );
}

